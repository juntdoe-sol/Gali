ORDER = list(ART)
# recolours of one drawing
VARIANTS = {
    'medal2': ('medal', {'y': 'g', 'l': 'w', 'Y': 'G'}),
    'medal3': ('medal', {'y': 'k', 'l': 's', 'Y': 'K'}),
}


def icon(name):
    src, swap = VARIANTS.get(name, (name, {}))
    rows = [r for r in ART[src].strip('\n').split('\n')]
    w, h = 14, 14
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = img.load()
    off_y = 1 + (h - len(rows)) // 2
    for y, row in enumerate(rows):
        row = row.ljust(w, '.')[:w]
        for x, ch in enumerate(row):
            if ch != '.':
                px[1 + x, off_y + y] = (*hexrgb(PAL[swap.get(ch, ch)]), 255)
    return outline_img(img, (30, 18, 44))


def names():
    return ORDER + list(VARIANTS)


def write(root):
    out = os.path.join(root, 'app/assets/icons')
    os.makedirs(out, exist_ok=True)
    for n in names():
        icon(n).resize((64, 64), Image.NEAREST).save(os.path.join(out, f'{n}.png'), optimize=True)
    return names()


if __name__ == '__main__':
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    write(root)
    import ui_icons  # noqa: E402

    ui_icons.write_index(root, list(ui_icons.ORDER) + names())
    print(f'{len(names())} interface icons written')
