def font_sprites(atlas):
    widths = {}
    for ch, rows in G.items():
        w = len(rows[0])
        img = Image.new('RGBA', (w, 5), (0, 0, 0, 0))
        px = img.load()
        for y, row in enumerate(rows):
            for x, v in enumerate(row):
                if v == '#':
                    px[x, y] = (255, 255, 255, 255)
        atlas.add(f'font-{ord(ch)}', img, 0, 0)
        widths[ch] = w
    return {'h': 5, 'gap': 1, 'space': 2, 'widths': widths}
