/** Draw a 1-bit mark with its top-left at (x, y). */
export function drawBits(g: Ctx, rows: string[], x: number, y: number, col: string) {
  g.fillStyle = col;
  for (let r = 0; r < rows.length; r++) {
    const row = rows[r];
    for (let i = 0; i < row.length; i++) if (row[i] === '#') g.fillRect(x + i, y + r, 1, 1);
  }
}
