// Regenerates app/src/tv/spriteMap.ts from the PNGs in tv/assets/sprites (run after make-sprites.py).
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '../assets/sprites');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.png')).sort();
let s = '/* Generated by tv/scripts/gen-sprite-map.js from tv/assets/sprites. Do not edit by hand. */\nimport type { ImageSourcePropType } from "react-native";\n\nexport const SPRITES: Record<string, ImageSourcePropType> = {\n';
for (const f of files) s += `  "${f.replace('.png', '')}": require("../../../tv/assets/sprites/${f}"),\n`;
s += '};\n';
fs.writeFileSync(path.join(__dirname, '../../app/src/tv/spriteMap.ts'), s);
console.log(files.length, 'sprites mapped');
